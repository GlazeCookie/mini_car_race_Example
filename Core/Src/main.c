/* 发车键低电平按下；确认按下后等待 2 秒。 */
static void WaitForRunKey(void)
{
  for (;;)
  {
    if (HAL_GPIO_ReadPin(GPIO_RUN_GPIO_Port, GPIO_RUN_Pin) == GPIO_PIN_RESET)
    {
      HAL_Delay(RUN_KEY_DEBOUNCE_MS);
      if (HAL_GPIO_ReadPin(GPIO_RUN_GPIO_Port, GPIO_RUN_Pin) == GPIO_PIN_RESET)
      {
        break;
      }
    }
    else
    {
      HAL_Delay(1U);
    }
  }

  HAL_Delay(RUN_START_DELAY_MS);
}
